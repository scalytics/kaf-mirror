#!/usr/bin/env python3
"""Assemble the static site into an output directory.

Stitches the hand-written page bodies with the shared header and footer,
copies styles and the favicon, and wraps the generated CLI reference
from web/docu/cli-commands.html with the same chrome.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from datetime import date, datetime, timezone
from pathlib import Path

WEBSITE = Path(__file__).resolve().parent
ROOT = WEBSITE.parent
PAGES = WEBSITE / "pages"
INCLUDES = WEBSITE / "includes"
# web/docu/cli-commands.html is regenerated by make docs-html and is the
# current CLI reference. docs/cli-commands.html is produced by a separate
# script that is not part of make docs-check, and can lag behind.
CLI_SRC = ROOT / "web" / "docu" / "cli-commands.html"

CLI_EXTRA_CSS = """
    /* Site chrome added by website/build.py around the generated CLI docs. */
    body { padding-top: 0 !important; }
    html, body { overflow-x: hidden; }
    /* Cap and center the CLI column the same way as the rest of the site.
       The generated sidebar is position: fixed, which would stick to the
       left of the viewport on a wide screen. Make it sticky inside the cap. */
    #content {
      max-width: var(--content);
      margin-inline: auto;
    }
    .container-fluid {
      display: flex;
      align-items: flex-start;
      max-width: 100%;
      min-width: 0;
    }
    .sidebar {
      position: sticky;
      top: 64px;
      left: auto;
      height: calc(100vh - 64px);
      flex: 0 0 300px;
      width: 300px;
      align-self: flex-start;
    }
    .content {
      flex: 1 1 auto;
      margin-left: 0;
      max-width: 100%;
      min-width: 0;
    }
    pre { max-width: 100%; overflow-x: auto; white-space: pre-wrap; overflow-wrap: break-word; }
    pre code { display: block; white-space: inherit; max-width: 100%; }
    @media (max-width: 900px) {
      .sidebar { display: none; }
      .content { margin-left: 0; max-width: 100%; padding: 20px; }
    }
"""


def mark_current(nav: str, current: str) -> str:
    token = 'data-nav="' + current + '"'
    return nav.replace(token, token + ' aria-current="page"')


def site_url(meta: dict) -> str:
    return meta["index.html"]["canonical"]


def render(text: str, site: str) -> str:
    return text.replace("{{SITE}}", site)


OG_IMAGE_PATH = "media/og-card.png"
OG_IMAGE_TYPE = "image/png"
OG_IMAGE_WIDTH = "1200"
OG_IMAGE_HEIGHT = "630"
OG_IMAGE_ALT = "kaf-mirror: Kafka backup you can watch, audit and trust"
CLI_TITLE = "CLI Command Reference - kaf-mirror"
CLI_DESCRIPTION = "Generated command reference for the kaf-mirror management CLI, mirror-cli."


def attr(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def social_meta(title: str, description: str, canonical: str, site: str) -> str:
    image = site + OG_IMAGE_PATH
    t = attr(title)
    d = attr(description)
    c = attr(canonical)
    img = attr(image)
    alt = attr(OG_IMAGE_ALT)
    return (
        "  <meta property=\"og:type\" content=\"website\">\n"
        f"  <meta property=\"og:title\" content=\"{t}\">\n"
        f"  <meta property=\"og:description\" content=\"{d}\">\n"
        f"  <meta property=\"og:url\" content=\"{c}\">\n"
        "  <meta property=\"og:site_name\" content=\"kaf-mirror\">\n"
        "  <meta property=\"og:locale\" content=\"en_US\">\n"
        f"  <meta property=\"og:image\" content=\"{img}\">\n"
        f"  <meta property=\"og:image:width\" content=\"{OG_IMAGE_WIDTH}\">\n"
        f"  <meta property=\"og:image:height\" content=\"{OG_IMAGE_HEIGHT}\">\n"
        f"  <meta property=\"og:image:alt\" content=\"{alt}\">\n"
        f"  <meta property=\"og:image:type\" content=\"{OG_IMAGE_TYPE}\">\n"
        "  <meta name=\"twitter:card\" content=\"summary_large_image\">\n"
        f"  <meta name=\"twitter:title\" content=\"{t}\">\n"
        f"  <meta name=\"twitter:description\" content=\"{d}\">\n"
        f"  <meta name=\"twitter:image\" content=\"{img}\">\n"
        f"  <meta name=\"twitter:image:alt\" content=\"{alt}\">\n"
    )


def jsonld_block(name: str, site: str) -> str:
    src = PAGES / (Path(name).stem + ".jsonld")
    if not src.is_file():
        return ""
    data = json.loads(render(src.read_text(encoding="utf-8"), site))
    payload = json.dumps(data, indent=2, ensure_ascii=False).replace("</", "<\\/")
    return "  <script type=\"application/ld+json\">\n" + payload + "\n  </script>\n"


def git_lastmod(*paths: Path) -> str:
    files = [str(p.resolve()) for p in paths if p.is_file()]
    if files:
        try:
            out = subprocess.check_output(
                ["git", "-C", str(ROOT), "log", "-1", "--format=%cs", "--", *files],
                text=True,
                stderr=subprocess.DEVNULL,
            ).strip()
            if out:
                return out
        except (subprocess.CalledProcessError, FileNotFoundError, OSError):
            pass
        newest = max(Path(f).stat().st_mtime for f in files)
        return datetime.fromtimestamp(newest, tz=timezone.utc).date().isoformat()
    return date.today().isoformat()


def sitemap(meta: dict, site: str) -> str:
    shared = [
        INCLUDES / "nav.html",
        INCLUDES / "footer.html",
        WEBSITE / "build.py",
        WEBSITE / "styles.css",
        WEBSITE / "media" / "og-card.png",
    ]
    rows = []
    for name, info in meta.items():
        if name == "404.html":
            continue
        sources = [PAGES / name, PAGES / (Path(name).stem + ".jsonld"), *shared]
        lm = git_lastmod(*sources)
        rows.append(f"  <url>\n    <loc>{info['canonical']}</loc>\n    <lastmod>{lm}</lastmod>\n  </url>\n")
    cli_lm = git_lastmod(CLI_SRC, PAGES / "cli-commands.jsonld", *shared)
    rows.append(
        f"  <url>\n    <loc>{site}cli-commands.html</loc>\n    <lastmod>{cli_lm}</lastmod>\n  </url>\n"
    )
    return (
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
        "<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n"
        f"{''.join(rows)}</urlset>\n"
    )


def shell(title: str, description: str, canonical: str, current: str, body: str, site: str, main_tag: bool = True, head_extra: str = "") -> str:
    nav = mark_current((INCLUDES / "nav.html").read_text(encoding="utf-8").rstrip(), current)
    footer = (INCLUDES / "footer.html").read_text(encoding="utf-8").rstrip()
    inner_open = "  <main id=\"content\">\n" if main_tag else "  <div id=\"content\">\n"
    inner_close = "  </main>\n" if main_tag else "  </div>\n"
    return (
        "<!DOCTYPE html>\n"
        "<html lang=\"en\">\n"
        "<head>\n"
        "  <meta charset=\"utf-8\">\n"
        "  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
        f"  <title>{attr(title)}</title>\n"
        f"  <meta name=\"description\" content=\"{attr(description)}\">\n"
        "  <meta name=\"color-scheme\" content=\"light dark\">\n"
        f"  <link rel=\"canonical\" href=\"{canonical}\">\n"
        "  <link rel=\"icon\" href=\"favicon.svg\" type=\"image/svg+xml\">\n"
        f"{social_meta(title, description, canonical, site)}"
        "  <link rel=\"stylesheet\" href=\"styles.css\">\n"
        f"{head_extra}"
        "</head>\n"
        "<body>\n"
        f"{nav}\n"
        f"{inner_open}"
        f"{body.rstrip()}\n"
        f"{inner_close}"
        f"{footer}\n"
        "</body>\n"
        "</html>\n"
    )


def wrap_cli(src: Path, site: str) -> str:
    text = src.read_text(encoding="utf-8")
    if "</head>" not in text or "<body>" not in text or "</body>" not in text:
        raise SystemExit(f"{src} is not a full HTML document")

    # The in-app docs page loads Bootstrap from a CDN and has a navbar that
    # points at /docu/. Drop both so the Pages site has no third-party
    # requests and uses the shared site header instead.
    text = re.sub(r'[ \t]*<link[^>]+bootstrap[^>]*>\s*', "", text, flags=re.I)
    text = re.sub(
        r'[ \t]*<script src="https://(?:code\.jquery\.com|cdn\.jsdelivr\.net|stackpath\.bootstrapcdn\.com)[^"]*"></script>\s*',
        "",
        text,
        flags=re.I,
    )
    text = re.sub(r'<nav class="navbar\b.*?</nav>\s*', "", text, count=1, flags=re.S)

    nav = mark_current((INCLUDES / "nav.html").read_text(encoding="utf-8").rstrip(), "cli-commands.html")
    footer = (INCLUDES / "footer.html").read_text(encoding="utf-8").rstrip()
    canonical = site + "cli-commands.html"
    social = social_meta(CLI_TITLE, CLI_DESCRIPTION, canonical, site)
    social = "    " + social.strip() + "\n"
    text = text.replace(
        "</head>",
        "    <meta name=\"description\" content=\"" + attr(CLI_DESCRIPTION) + "\">\n"
        "    <link rel=\"icon\" href=\"favicon.svg\" type=\"image/svg+xml\">\n"
        + social +
        "    <link rel=\"canonical\" href=\"" + attr(canonical) + "\">\n"
        + jsonld_block("cli-commands.html", site) +
        f"    <style>{CLI_EXTRA_CSS}</style>\n"
        "</head>",
        1,
    )
    # The generated page already has <main class="content">, so the skip
    # target is a wrapping div rather than a second main landmark.
    text = text.replace("<body>", "<body>\n" + nav + "\n  <div id=\"content\">\n", 1)
    text = text.replace("</body>", "  </div>\n" + footer + "\n</body>", 1)
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the kaf-mirror static site.")
    parser.add_argument(
        "outdir",
        nargs="?",
        default=str(ROOT / "_site"),
        help="Output directory (default: <repo>/_site)",
    )
    args = parser.parse_args()
    out = Path(args.outdir).resolve()
    if not CLI_SRC.is_file():
        print(f"missing {CLI_SRC}", file=sys.stderr)
        return 1
    meta = json.loads((PAGES / "pages.json").read_text(encoding="utf-8"))
    site = site_url(meta)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    shutil.copy2(WEBSITE / "styles.css", out / "styles.css")
    shutil.copy2(WEBSITE / "favicon.svg", out / "favicon.svg")
    fonts_src = WEBSITE / "fonts"
    if fonts_src.is_dir():
        shutil.copytree(fonts_src, out / "fonts", dirs_exist_ok=True)
    media_src = WEBSITE / "media"
    if media_src.is_dir():
        shutil.copytree(media_src, out / "media")
    llms = WEBSITE / "llms.txt"
    if llms.is_file():
        (out / "llms.txt").write_text(render(llms.read_text(encoding="utf-8"), site), encoding="utf-8")
    for name, info in meta.items():
        body = (PAGES / name).read_text(encoding="utf-8")
        html = shell(
            info["title"],
            info["description"],
            info["canonical"],
            info["nav"],
            body,
            site,
            head_extra=jsonld_block(name, site),
        )
        (out / name).write_text(html, encoding="utf-8")
    (out / "cli-commands.html").write_text(wrap_cli(CLI_SRC, site), encoding="utf-8")
    (out / "sitemap.xml").write_text(sitemap(meta, site), encoding="utf-8")
    (out / "robots.txt").write_text(f"User-agent: *\nAllow: /\n\nSitemap: {site}sitemap.xml\n", encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    print(f"Wrote site to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
